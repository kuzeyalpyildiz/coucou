// Produce a self-contained sidecar: users installing the integration do not
// need npm, node_modules, or a network download on their own computer.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { readFileSync } from "node:fs";

const outfile = process.argv[2];
if (!outfile) throw new Error("Expected the OpenCode client output filename");
const license = readFileSync(new URL("./licenses/opencode-MIT.txt", import.meta.url), "utf8");

const result = await build({
  stdin: {
    contents: 'export { OpenCode } from "@opencode/client"; export { Service } from "@opencode/client/service";',
    resolveDir: fileURLToPath(new URL("../", import.meta.url)),
    sourcefile: "coucou-opencode-client.mjs",
    loader: "js",
  },
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  minify: true,
  legalComments: "eof",
  metafile: true,
  banner: { js: `// Coucou OpenCode client — generated by Coucou. Bundled @opencode/client 2.0.29 (MIT).\n/*\n${license}\n*/` },
});

// A build must fail, rather than ship a sidecar that still needs npm packages.
for (const output of Object.values(result.metafile.outputs)) {
  if (output.bytes > 2 * 1024 * 1024) throw new Error("OpenCode client bundle exceeds its 2 MiB size budget");
  for (const dependency of output.imports) {
    if (dependency.external && !dependency.path.startsWith("node:")) {
      throw new Error(`OpenCode client has an unbundled dependency: ${dependency.path}`);
    }
  }
}
