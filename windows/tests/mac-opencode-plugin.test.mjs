import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { EventEmitter } from 'node:events';
import vm from 'node:vm';

// Exercise the actual JavaScript emitted by the macOS Swift installer, not a copy.
const swift = readFileSync(new URL('../../NotchBuddy/Sources/App/HookServer.swift', import.meta.url), 'utf8');
const start = swift.indexOf('// Coucou hook plugin for OpenCode — generated by Coucou.app');
assert.ok(start >= 0);
const source = swift.slice(start, swift.indexOf('"""', start))
  .replace('\\(path)', '/private/Coucou/nb-hook').replaceAll('\\\\n', '\\n');

async function fixture(events = []) {
  const calls = [], hooks = new Map(), disposed = [];
  const context = vm.createContext({ setTimeout, clearTimeout, AbortController, AbortSignal,
    console: { warn() {} } });
  const transport = new vm.SyntheticModule(['spawn'], function () {
    this.setExport('spawn', (exe, args) => {
      assert.equal(exe, '/bin/sh');
      assert.deepEqual(Array.from(args), ['/private/Coucou/nb-hook', '--agent', 'opencode']);
      const child = new EventEmitter();
      child.stdin = new EventEmitter();
      child.stdin.write = (data) => calls.push(JSON.parse(data));
      child.stdin.end = () => queueMicrotask(() => child.emit('close', 0));
      child.kill = () => child.emit('close', 0);
      child.unref = () => {};
      return child;
    });
  }, { context });
  const module = new vm.SourceTextModule(source, { context });
  await module.link(() => transport);
  await module.evaluate();
  const register = (domain) => async (name, callback) => {
    hooks.set(`${domain}.${name}`, callback);
    return { dispose: async () => disposed.push(`${domain}.${name}`) };
  };
  const cleanup = await module.namespace.default.setup({
    location: { directory: '/project' },
    session: { hook: register('session'), get: async () => ({ location: { directory: '/session' } }) },
    tool: { hook: register('tool') },
    event: { subscribe: ({ signal }) => ({ async *[Symbol.asyncIterator]() {
      for (const event of events) yield event;
      if (!signal.aborted) await new Promise((resolve) => signal.addEventListener('abort', resolve, { once: true }));
    } }) },
  });
  await new Promise(setImmediate);
  return { calls, hooks, disposed, cleanup, legacy: module.namespace.CoucouPlugin };
}

test('macOS V2 forwards native execution success, never idle or intermediate model completion', async () => {
  const f = await fixture(['session.idle', 'session.status', 'model.completed', 'session.execution.succeeded']
    .map((type) => ({ type, data: { sessionID: 'one' } })));
  try {
    assert.deepEqual(f.calls.map((c) => c.hook_event_name), ['Stop']);
    assert.equal(f.calls[0].session_id, 'one');
    assert.equal(f.calls[0].cwd, '/session');
  } finally { await f.cleanup(); }
  assert.equal(f.disposed.length, 3);
});

test('macOS V2 ignores events for other locations and leaves decisions native', async () => {
  const f = await fixture([
    { type: 'session.created', location: { directory: '/other' }, data: { sessionID: 'other' } },
    { type: 'permission.asked', data: { sessionID: 'one' } },
    { type: 'form.created', data: { form: { sessionID: 'one' } } },
  ]);
  try { assert.deepEqual(f.calls, []); }
  finally { await f.cleanup(); }
});

test('macOS V2 reports prompts and tool outcomes without forwarding private input', async () => {
  const f = await fixture();
  try {
    await f.hooks.get('session.prompt')({ sessionID: 'one', prompt: { text: 'secret' } });
    await f.hooks.get('tool.execute.before')({ sessionID: 'one', tool: 'read', input: { token: 'secret' } });
    await f.hooks.get('tool.execute.after')({ sessionID: 'one', tool: 'read', status: 'error', error: 'secret' });
    assert.deepEqual(f.calls.map((c) => c.hook_event_name), ['UserPromptSubmit', 'PreToolUse', 'PostToolUseFailure']);
    assert.equal(JSON.stringify(f.calls).includes('secret'), false);
  } finally { await f.cleanup(); }
  await f.hooks.get('session.prompt')({ sessionID: 'one' });
  assert.equal(f.calls.length, 3, 'disposed plugin must not forward more work');
});

test('macOS retains the legacy entrypoint without relaying permission requests', async () => {
  const f = await fixture();
  try {
    const legacy = await f.legacy({});
    await legacy.event({ event: { type: 'permission.asked', properties: { sessionID: 'one' } } });
    await legacy.event({ event: { type: 'session.created', properties: { sessionID: 'one', input: { token: 'secret' } } } });
    assert.deepEqual(f.calls.map((c) => c.hook_event_name), ['SessionStart']);
    assert.equal(JSON.stringify(f.calls).includes('secret'), false);
  } finally { await f.cleanup(); }
});
