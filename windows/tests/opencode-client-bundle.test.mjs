import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { spawnSync } from "node:child_process";

test("the shipped OpenCode client loads from an empty folder without user-installed npm dependencies", async () => {
  const scratch = mkdtempSync(join(tmpdir(), "coucou-client-"));
  try {
    const output = join(scratch, "client.mjs");
    const script = fileURLToPath(new URL("../scripts/bundle-opencode-client.mjs", import.meta.url));
    const result = spawnSync(process.execPath, [script, output], { encoding: "utf8", timeout: 30_000 });
    assert.equal(result.status, 0, result.stderr || String(result.error));
    const contents = readFileSync(output, "utf8");
    assert.ok(contents.includes("generated by Coucou"));
    assert.ok(contents.includes("Copyright (c) 2025 opencode"));
    const client = await import(pathToFileURL(output).href);
    assert.equal(typeof client.OpenCode.make, "function");
    assert.equal(typeof client.Service.discover, "function");
    assert.equal(typeof client.Service.headers, "function");
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
});
